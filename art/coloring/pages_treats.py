def candy():
    o = ""
    # lollipops
    for x, y, r in [(260, 260, 120), (760, 240, 100)]:
        o += R(x - 10, y + r - 6, 20, 380 - r, 8)
        o += C(x, y, r)
        d = f"M{x} {y}"
        for i in range(1, 40):
            a = i * 0.45
            rr = r * i / 40
            d += f" L{x + math.cos(a) * rr:.1f} {y + math.sin(a) * rr:.1f}"
        o += L(d, w=5)
        o += P(f"M{x - 10} {y + r + 30} L{x - 50} {y + r + 10} Q{x - 54} {y + r + 40} {x - 50} {y + r + 70} Z", w=5)
