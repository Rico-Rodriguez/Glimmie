    tx, ty = x + 14, y - h
    for dx, dy in [(-110, 30), (-90, -40), (0, -70), (100, -30), (110, 40)]:
        o += P(f"M{tx} {ty} Q{tx + dx * 0.6} {ty + dy - 30} {tx + dx} {ty + dy} Q{tx + dx * 0.5} {ty + dy * 0.3} {tx} {ty} Z", w=5)
    o += C(tx - 10, ty + 14, 12, w=4) + C(tx + 12, ty + 16, 12, w=4)
    return o


