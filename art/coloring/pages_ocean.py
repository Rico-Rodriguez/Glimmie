def shell(x, y, s=1.0):
    o = P(f"M{x - 40 * s} {y} C{x - 50 * s} {y - 50 * s} {x + 50 * s} {y - 50 * s} {x + 40 * s} {y} Z", w=5)
    for dx in (-20, 0, 20):
        o += L(f"M{x} {y} L{x + dx * s} {y - 36 * s}", w=3.5)
    return o


def fish(x, y, s=1.0, flip=False):
    b = (P("M60 0 C40 -60 -60 -60 -80 0 C-60 60 40 60 60 0 Z")
         + P("M50 0 L110 -46 Q100 0 110 46 Z")
         + P("M-20 -42 Q0 -80 30 -44 Z", w=5)
         + L("M-20 -40 Q-40 0 -20 40", w=4) + L("M10 -40 Q-10 0 10 40", w=4)
         + eyes(-50, -6, 0, 1.2) + smile(-62, 16, 0.7))
    return G(b, x, y, s, flip=flip)


