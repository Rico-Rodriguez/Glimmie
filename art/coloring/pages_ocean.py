def seaweed(x, y, h, s=1.0):
    return P(f"M{x - 10 * s} {y} C{x - 40 * s} {y - h * 0.3} {x + 20 * s} {y - h * 0.5} {x - 10 * s} {y - h * 0.8} Q{x} {y - h} {x + 10 * s} {y - h * 0.8} "
             f"C{x + 40 * s} {y - h * 0.5} {x - 10 * s} {y - h * 0.3} {x + 14 * s} {y} Z", w=5)


